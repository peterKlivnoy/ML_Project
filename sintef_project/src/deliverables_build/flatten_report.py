"""Single-file report source: report/Report.tex with preamble.tex and the lab-log entries inlined.

The report is written as report/Report.tex + report/preamble.tex + report/log/*.tex (the full lab
log, Appendix B) + report/figures/. This writes

    deliverables/Report.tex         one self-contained .tex (compiles in place: finds ../report/figures)
    deliverables/Report_source.zip  that .tex plus the figures it uses (unzip and run pdflatex twice,
                                    or upload to Overleaf)

Edit the sources in report/ and re-run this script; the outputs are generated.
"""
from __future__ import annotations

import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "report"
OUT = ROOT / "deliverables"

HEADER = """% Single-file version of the report: report/Report.tex with report/preamble.tex and the
% lab-log entries (report/log/*.tex) inlined. Generated by src/deliverables_build/flatten_report.py;
% edit the sources in report/ and re-run it. Compile with pdflatex (twice, for the contents and
% cross-references). Figures are read from figures/ next to this file, or from ../report/figures/.
"""


def inline(text: str) -> str:
    def sub(m):
        name = m.group(1)
        path = REPORT / (name if name.endswith(".tex") else name + ".tex")
        body = path.read_text().rstrip("\n")
        return f"% ---- begin {path.relative_to(REPORT)} ----\n{body}\n% ---- end {path.relative_to(REPORT)} ----"
    return re.sub(r"^\\input\{([^}]+)\}[ \t]*$", sub, text, flags=re.M)


def main():
    src = (REPORT / "Report.tex").read_text()
    flat = inline(src)
    assert "\\input{" not in flat, "an \\input was left unexpanded"
    # figures resolve next to the file (zip) or in the repository's report/ folder (in place)
    flat = flat.replace("\\begin{document}", "\\graphicspath{{./}{../report/}}\n\n\\begin{document}", 1)
    flat = HEADER + flat
    (OUT / "Report.tex").write_text(flat)

    figs = sorted(set(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", flat)))
    with zipfile.ZipFile(OUT / "Report_source.zip", "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("Report.tex", flat)
        for f in figs:
            p = REPORT / f
            if not p.exists():
                p = REPORT / (f + ".png")
                f = f + ".png"
            z.write(p, f)
    print(f"wrote {OUT / 'Report.tex'} ({flat.count(chr(10))} lines) and Report_source.zip "
          f"({len(figs)} figures)")


if __name__ == "__main__":
    main()
